// Hilfsfunktion um PLZ-Präfix zu extrahieren
export const getPlzPrefix = (plz) => {
  if (!plz || typeof plz !== 'string') return null;
  return plz.substring(0, 2);
};

// Koordinaten für eine PLZ abrufen
export const getCoordinatesForPlz = (plz) => {
  const prefix = getPlzPrefix(plz);
  return plzCoordinates[prefix] || null;
};
